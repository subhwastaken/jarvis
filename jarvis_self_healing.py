# Approved binaries for self-healing repair execution (shell=False only)
SAFE_BASH_BINARIES = {
    "open", "pkill", "defaults", "afplay", "pmset", "killall",
    "screencapture", "say"
}

DANGEROUS_SHELL_PATTERNS = re.compile(
    r"[;&|`$><]|(?:\b(?:rm|dd|mkfs|chmod|chown|sudo|curl|wget|nc|bash|sh|zsh|eval|exec|python|perl|ruby)\b)",
    re.I
)


def is_safe_command(cmd_type: str, cmd: str) -> tuple[bool, str, list[str] | None]:
    """Strictly validates commands generated by self-healing to prevent arbitrary code execution."""
    if not cmd or not isinstance(cmd, str):
        return False, "Empty or invalid command format", None

    clean_cmd = cmd.strip()

    if cmd_type == "applescript":
        # Disallow arbitrary shell execution via AppleScript escape hatch
        if "do shell script" in clean_cmd.lower():
            return False, "AppleScript containing 'do shell script' is forbidden for security", None
        return True, "OK", ["osascript", "-e", clean_cmd]

    elif cmd_type == "bash":
        # Block dangerous shell operators and commands
        if DANGEROUS_SHELL_PATTERNS.search(clean_cmd):
            return False, f"Command contains forbidden shell metacharacters or dangerous binaries: {clean_cmd}", None

        try:
            tokens = shlex.split(clean_cmd)
        except Exception as e:
            return False, f"Command cannot be safely parsed: {e}", None

        if not tokens:
            return False, "No executable tokens found", None

        binary = os.path.basename(tokens[0]).lower()
        if binary not in SAFE_BASH_BINARIES:
            return False, f"Binary '{binary}' is not in approved safe binaries whitelist", None

        return True, "OK", tokens

    return False, f"Unsupported command type '{cmd_type}'", None

LEARNED_STORE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "learned_actions.json")
OLLAMA_HOST = os.getenv("OLLAMA_HOST", "http://localhost:11434")
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "qwen3:1.7b")
NVIDIA_KEY = os.getenv("NVIDIA_API_KEY", "")


class LearnedActionStore:
    """Episodic memory store for dynamically healed actions."""
    def __init__(self, filepath=LEARNED_STORE_PATH):
        self.filepath = filepath
        self.rules = {}
        self.load()

    def load(self):
        if os.path.exists(self.filepath):
            try:
                with open(self.filepath, "r", encoding="utf-8") as f:
                    self.rules = json.load(f)
            except Exception as e:
                print(f"  [LearnedStore] Error reading store: {e}")
                self.rules = {}
        else:
            self.rules = {}

    def save(self):
        try:
            with open(self.filepath, "w", encoding="utf-8") as f:
                json.dump(self.rules, f, indent=2)
        except Exception as e:
            print(f"  [LearnedStore] Error writing store: {e}")

    def normalize(self, query: str) -> str:
        q = query.lower().strip(" .!?,;\"'")
        q = re.sub(r'^(?:(?:hey|hi|hello|ok|okay)?\s*(?:jarvis|siri|friday|jev)[,\s]*)+', '', q).strip()
        q = re.sub(r'^(?:please|could you|can you)\s+', '', q).strip()
        return q

    def get(self, query: str):
        clean = self.normalize(query)
        if clean in self.rules:
            return self.rules[clean]
        # Check fuzzy match
        for stored_query, entry in self.rules.items():
            ratio = difflib.SequenceMatcher(None, clean, stored_query).ratio()
            if ratio >= 0.88:
                return entry
        return None

    def learn(self, query: str, action_type: str, payload: dict, spoken_reply: str):
        clean = self.normalize(query)
        if not clean:
            return
        self.rules[clean] = {
            "type": action_type,
            "payload": payload,
            "reply": spoken_reply,
            "learned_at": time.time(),
            "hit_count": 1
        }
        self.save()
        print(f"  [Self-Healing] Committed new learned rule for: '{clean}' -> {action_type}")


_STORE = LearnedActionStore()


def get_learned_store() -> LearnedActionStore:
    return _STORE


